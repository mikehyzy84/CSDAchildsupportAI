function h1(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 360, after: 200 }, children: [new TextRun({ text, bold: true, size: 32, color: NAVY })] });
}
function h2(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 120 }, children: [new TextRun({ text, bold: true, size: 26, color: TEAL })] });
}
function h3(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_3, spacing: { before: 160, after: 80 }, children: [new TextRun({ text, bold: true, size: 22, color: NAVY })] });
}
function p(text, opts = {}) {
  return new Paragraph({ spacing: { after: 100 }, ...opts, children: [new TextRun({ text, size: 22 })] });
}
function code(text) {
  return new Paragraph({ spacing: { after: 40 }, indent: { left: 360 }, children: [new TextRun({ text, font: 'Courier New', size: 19, color: '333333' })] });
}
function bullet(text, level = 0) {
  return new Paragraph({ bullet: { level }, spacing: { after: 60 }, children: [new TextRun({ text, size: 22 })] });
}
function pageBreak() {
  return new Paragraph({ pageBreakBefore: true });
}

